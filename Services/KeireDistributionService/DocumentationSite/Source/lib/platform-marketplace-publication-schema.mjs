const uuid = "CHAR(36) CHARACTER SET ascii COLLATE ascii_bin";
const time = "DATETIME(6)";
const hash = (name) => `REGEXP_LIKE(${name}, '^[0-9a-f]{64}$', 'c')`;

function publicKeyTable(name) {
    return {
        name,
        columns: {
            key_id: "VARCHAR(64) NOT NULL",
            algorithm: "VARCHAR(16) NOT NULL",
            public_key_base64: "VARCHAR(44) NOT NULL",
            fingerprint: "VARCHAR(71) NOT NULL",
            active: "BOOLEAN NOT NULL",
            valid_from: `${time} NOT NULL`,
            valid_until: `${time} NULL`,
            created_at: `${time} NOT NULL`,
        },
        extra: [
            "PRIMARY KEY (key_id)",
            "UNIQUE (fingerprint)",
            "CHECK (algorithm = 'ed25519')",
            "CHECK (REGEXP_LIKE(key_id, '^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$', 'c'))",
            "CHECK (REGEXP_LIKE(fingerprint, '^sha256:[0-9a-f]{64}$', 'c'))",
            "CHECK (REGEXP_LIKE(public_key_base64, '^[A-Za-z0-9+/]{43}=$', 'c'))",
            "CHECK (valid_until IS NULL OR valid_until > valid_from)",
            "CHECK (active IN (0,1))",
        ],
    };
}

